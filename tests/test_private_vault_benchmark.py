def _cli_files(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> tuple[Path, Path, Path]:
    local = tmp_path / "retrieval" / "local"
    local.mkdir(parents=True)
    monkeypatch.setattr(
        private_vault, "__file__", str(tmp_path / "retrieval/private_vault.py")
    )
    scope = tmp_path / "scope.json"
    scope.write_text(
        json.dumps(
            {"vault_path": "/fixture", "index_root": ".", "folder_rules": {".": "read"}}
        )
    )
    cases = tmp_path / "cases.jsonl"
    cases.write_text(
        json.dumps(
            {
                "id": "case1",
                "query": "private query sentinel",
                "expected_paths": ["a.md"],
            }
        )
        + "\n"
    )
    return scope, cases, local / "baseline.json"


def test_compare_reports_metrics_and_redacts_paths_by_default(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    scope, cases, baseline_path = _cli_files(tmp_path, monkeypatch)
    prior = {
        "scope_sha256": "0" * 64,
        "cases_sha256": "0" * 64,
        "corpus_sha256": "0" * 64,
        "metrics": {"hit@5": 0.0, "mrr": 0.0, "negative_accuracy": None},
        "case_results": {
            "case1": {
                "rank": None,
                "selected_paths": ["private/path.md"],
                "relevant_hit": False,
            }
        },
    }
    baseline_path.write_text(json.dumps(prior))
    current = {
        **prior,
        "case_results": {
            "case1": {
                "rank": 1,
                "selected_paths": ["private/path.md"],
                "relevant_hit": True,
            }
        },
    }
    monkeypatch.setattr(private_vault, "run_private_benchmark", lambda *_: current)
    # Use hashes matching the deterministic values generated by the run.
    scope_obj, case_obj = load_scope(scope), load_cases(cases)
    current["scope_sha256"] = hashlib.sha256(
        json.dumps(scope_obj, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    current["cases_sha256"] = hashlib.sha256(
        json.dumps(case_obj, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    prior.update(
        scope_sha256=current["scope_sha256"], cases_sha256=current["cases_sha256"]
    )
    prior["metrics"] = {"hit@5": 0.0, "mrr": 0.0, "negative_accuracy": None}
    baseline_path.write_text(json.dumps(prior))
    current["metrics"] = {"hit@5": 1.0, "mrr": 1.0, "negative_accuracy": None}
    assert (
        private_vault.main(
            ["--scope", str(scope), "--cases", str(cases), "--compare-baseline"]
        )
        == 0
    )
    output = capsys.readouterr().out
    assert "private/path.md" not in output and "private query sentinel" not in output
    report = json.loads(output)
    assert report["metric_deltas"]["mrr"] == 1.0
    assert report["case_deltas"]["case1"]["after_rank"] == 1
    assert report["baseline_metrics"] == prior["metrics"]


